SOLAR_TERM_DATES: Final[dict[int, dict[int, tuple[int, int]]]] = {
    index: SOLAR_TERM_DATES_BY_NAME[name]
    for index, name in enumerate(SOLAR_TERM_NAMES)
}

def get_solar_term_date_by_name(year: int, term_name: str) -> date | None:
    """获取指定年份、节气名称对应的公历日期。"""
    table = SOLAR_TERM_DATES_BY_NAME.get(term_name)
    if not table:
        return None
    month_day = table.get(year)
    if not month_day:
        return None
    return date(year, month_day[0], month_day[1])

def get_solar_term_date(year: int, term_index: int) -> date | None:
    """获取指定年份、节气索引对应的公历日期。

    Args:
        year: 公历年份
        term_index: 节气索引 0-23（立春起始）

    Returns:
        日期或 None（未覆盖）
    """
    if term_index < 0 or term_index >= len(SOLAR_TERM_NAMES):
        return None
    return get_solar_term_date_by_name(year, SOLAR_TERM_NAMES[term_index])

